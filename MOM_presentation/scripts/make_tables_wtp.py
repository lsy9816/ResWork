"""make_tables_wtp -- deck tables on the WTP basis (pay given up; employers = pay cut required), from data/wtp_deck.csv.
Writes T_gap, T_org_pct, T_emp_robust, T_org_robust into OUT (the overleaf_upload/tables folder).
usage: python3 make_tables_wtp.py OUT_DIR
"""
import math
import sys
from pathlib import Path

import pandas as pd

MOM = Path(__file__).resolve().parents[1]
OUT = Path(sys.argv[1])
D = pd.read_csv(MOM / "data" / "wtp_deck.csv")
M = r"\textcolor{Muted}{%s}"


def r0(x):
    v = int(math.floor(abs(x) + 0.5))
    return ("$-$" if x < 0 and v else "") + str(v)


def r1(x):
    s = f"{abs(x):.1f}"
    return ("$-$" if x < 0 and float(s) else "") + s


def row(side, item, sample="main", split="all", group=0):
    q = D[(D.side == side) & (D["sample"] == sample) & (D.split == split) & (D.group == group) & (D["item"] == item)]
    return q.iloc[0]


def tab(widths, aligns, head, rows, note, spacing="3pt", total=None):
    cs = ""
    for i, (w, a) in enumerate(zip(widths, aligns)):
        cs += ">{\\raggedleft\\arraybackslash}" if a == "r" else ">{\\raggedright\\arraybackslash}"
        cs += f"p{{{w:.2f}cm}}" + ("@{\\hspace{0.25cm}}" if i < len(widths) - 1 else "")
    hd = []
    for i, (w, a, h) in enumerate(zip(widths, aligns, head)):
        al = ">{\\raggedleft\\arraybackslash}" if a == "r" else ">{\\raggedright\\arraybackslash}"
        hs = "@{\\hspace{0.25cm}}" if i < len(widths) - 1 else ""
        hd.append(f"\\multicolumn{{1}}{{@{{}}{al}b{{{w:.2f}cm}}{hs}}}{{\\textbf{{{h}}}}}")
    body = ""
    for r in rows:
        if r == "MID":
            body += "\\midrule\n"
            continue
        body += " & ".join(r) + " \\\\\n\\addlinespace[%s]\n" % spacing
    tw = total or (sum(widths) + 0.25 * (len(widths) - 1))
    n = len(widths)
    return ("\\begin{tabular}{@{}" + cs + "@{}}\n\\toprule\n" + " & ".join(hd) + " \\\\\n\\midrule\n" + body +
            "\\bottomrule\n\\addlinespace[3pt]\n"
            f"\\multicolumn{{{n}}}{{@{{}}>{{\\raggedright\\arraybackslash}}p{{{tw:.2f}cm}}@{{}}}}{{\\leavevmode\\color{{Muted}}"
            "\\fontsize{8.7}{9.8}\\selectfont " + note + "} \\\\\n\\end{tabular}\n")


def write(name, header, text):
    (OUT / f"{name}.tex").write_text(f"% generated by scripts/make_tables_wtp.py from data/wtp_deck.csv ({header}); do not edit by hand\n" + text,
                                     encoding="utf-8")


ARR = [("Compressed week", "t2", "A: common ground"), ("1--2 days WFH", "p1", "B: depends on the role"),
       ("3--4 days WFH", "p2", "C: far apart"), ("Fully remote", "p3", "C: far apart"),
       ("Staggered hours", "t1", "Little at stake"), ("Job sharing / reduced load", "l1", "Pay for hours"),
       ("Part-time", "l2", "Pay for hours")]


def gap(item):
    p = row("pme", item)
    e = row("emp", item)
    g = e.giveup - p.giveup
    se = math.hypot(p.se, e.se)
    return p, e, g, g - 1.96 * se, g + 1.96 * se, math.erfc(abs(g / se) / math.sqrt(2))


def ci(x, lo, hi):
    return f"{r0(x)} [{r0(lo)}, {r0(hi)}]"


# ---- T_gap: B-gap
rows = []
for lab, it, zone in ARR:
    p, e, g, lo, hi, pv = gap(it)
    gtxt = f"{r0(g)} [{r0(lo)}, {r0(hi)}]" + (", n.s." if lo <= 0 <= hi else "")
    rows.append([lab, M % ci(p.giveup, p.lb, p.ub), M % ci(e.giveup, e.lb, e.ub), M % gtxt, zone])
write("T_gap", "B-gap", tab([3.10, 2.20, 2.45, 2.45, 3.60], "lrrrl", ["Arrangement", "PMEs give up, \\%", "Employers require, \\%",
                                                                  "Gap, points", "Zone"], rows,
    "Gap = employers' cut minus PMEs' give-up (\\% of pay, 95\\% CI). Indicative. n.s. = not significant at 5\\%."))

# ---- T_org_pct: B-org-pct
OP = [("1--2 days WFH (onsite)", "p1", "Direction robust"), ("3--4 days WFH (onsite)", "p2", ""),
      ("Fully remote (onsite)", "p3", ""), ("Staggered hours (fixed hours)", "t1", "\\emph{not robust} (version clusters)"),
      ("Compressed week (fixed hours)", "t2", "No detectable reservation; mostly the cheaper candidate"),
      ("4-day reduced load (full-time)", "l1", "\\ensuremath{\\approx} pro-rata for fewer hours"),
      ("Part-time (full-time)", "l2", "\\ensuremath{\\approx} pro-rata for fewer hours"),
      ("High turnover risk \\ensuremath{>}20\\% (\\ensuremath{<}10\\%)", "r2", "Benchmark"),
      ("Moderate turnover risk 10--20\\% (\\ensuremath{<}10\\%)", "r1", "Robust: no detectable reservation")]
rows = []
for lab, it, st in OP:
    e = row("emp", it)
    rows.append([lab, M % r0(e.giveup), M % f"{r0(e.lb)} to {r0(e.ub)}", st])
write("T_org_pct", "B-org-pct", tab([5.50, 1.70, 1.80, 4.75], "lrrl", ["Candidate (vs base)", "Pay cut, \\%", "95\\% CI", "Status"], rows,
    "Pay cut at which employers would be indifferent between the candidates (positive = cut required). Indicative.", spacing="1pt"))

# ---- T_emp_robust: B-emp-robust (PMEs)
cols = [("Main", "main"), ("Excl.\\ outliers", "excl_salary_out"), ("1\\% trim", "trim1pct"), ("Excl.\\ same-side", "same_side"),
        ("Position term", "left_asc")]
RR = [("1--2 days WFH", "p1"), ("3--4 days WFH", "p2"), ("Fully remote", "p3"), ("Compressed week", "t2"),
      ("Staggered hours", "t1"), ("Job sharing", "l1"), ("Part-time", "l2")]
ns = {c: int(row("pme", "p1", c).n) for _, c in cols}
rows = [["N"] + [f"{ns[c]:,}" for _, c in cols] + ["1,020"], "MID"]
for lab, it in RR:
    vc = row("pme", it, "version_cluster")
    rows.append([lab] + [M % ("\\ensuremath{\\approx}" + r1(row("pme", it, c).giveup)) for _, c in cols] +
                [M % f"{r0(vc.lb)}--{r0(vc.ub)}"])
w = [3.20, 1.30, 1.55, 1.30, 1.55, 1.50, 1.45]
write("T_emp_robust", "B-emp-robust", tab(w, "lrrrrrr", ["", *[h for h, _ in cols], "Version CI"], rows,
    "\\% of pay given up. Version CI: 95\\% CI clustered by survey version.", total=14.40))

# ---- T_org_robust: B-org-robust (employers)
cols = [("Main", "main"), ("Excl.\\ outliers", "excl_salary_out"), ("1\\% trim", "trim1pct"), ("Excl.\\ same-side", "same_side")]
ns = {c: int(row("emp", "p1", c).n) for _, c in cols}
rows = [["N"] + [f"{ns[c]:,}" for _, c in cols], "MID"]
ER = [("1--2 days WFH", "p1"), ("3--4 days WFH", "p2"), ("Fully remote", "p3"), ("Compressed week", "t2"),
      ("Staggered hours", "t1"), ("Reduced load", "l1"), ("Part-time", "l2")]
for lab, it in ER:
    rows.append([lab] + [M % ("\\ensuremath{\\approx}" + r1(row("emp", it, c).giveup)) for _, c in cols])
write("T_org_robust", "B-org-robust", tab([4.00, 1.90, 2.30, 1.90, 2.40][:5], "lrrrr", ["", *[h for h, _ in cols]], rows,
    "\\% pay cut employers would require. Outliers: implausible salaries; same-side: always chose one side.", total=12.50))
print("ok")
