"""make_table_fwa_current -- tables/T_fwa_current.tex for backup B-fwa-current (users vs non-users of each arrangement).
Source: results_fwa/fwa_current.csv (current-arrangement interaction model of code_final.do; employed PMEs, n = 1,004).
Pay given up in % of pay; difference = users minus non-users, 95% CI; bold = interval excludes 0."""
import pandas as pd, pathlib
R = pathlib.Path(__file__).resolve().parents[1]
d = pd.read_csv(R / "results_fwa" / "fwa_current.csv")
order = ["1–2 days WFH", "3–4 days WFH", "Fully remote", "Compressed week", "Staggered hours", "Job sharing", "Part-time"]
d = d.set_index("arrangement").loc[order]
def f(x):
    v = round(x)
    return f"{abs(v)}" if v >= 0 else f"$-${abs(v)}"
rows = []
for a, r in d.iterrows():
    sig = (r.diff_lb > 0) or (r.diff_ub < 0)
    diff = f"{f(r['diff'])} [{f(r.diff_lb)}, {f(r.diff_ub)}]"
    if sig: diff = "\\textbf{" + diff + "}"
    rows.append(f"{a.replace('–', '--')} & {int(r.n_users)} & {f(r.giveup_nonusers)} & {f(r.giveup_users)} & {diff} \\\\")
    rows.append("\\addlinespace[2pt]")
tex = ("% generated by scripts/make_table_fwa_current.py from results_fwa/fwa_current.csv (B-fwa-current); do not edit by hand\n"
"\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{3.6cm}@{\\hspace{0.25cm}}>{\\raggedleft\\arraybackslash}p{1.5cm}@{\\hspace{0.25cm}}>{\\raggedleft\\arraybackslash}p{2.4cm}@{\\hspace{0.25cm}}>{\\raggedleft\\arraybackslash}p{2.0cm}@{\\hspace{0.25cm}}>{\\raggedleft\\arraybackslash}p{3.3cm}@{}}\n"
"\\toprule\n\\textbf{Arrangement} & \\textbf{Users (n)} & \\textbf{Non-users give up} & \\textbf{Users give up} & \\textbf{Difference [95\\% CI]} \\\\\n\\midrule\n"
+ "\n".join(rows[:-1]) + "\n\\bottomrule\n\\end{tabular}\n")
(R / "overleaf_upload" / "tables" / "T_fwa_current.tex").write_text(tex)
print(tex)
